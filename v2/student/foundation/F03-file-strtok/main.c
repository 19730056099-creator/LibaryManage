/*
 * F03 分步教学版：文件读写 + strtok 字符串切割
 *
 * 整个程序 = 4 个小步骤：
 *   步骤1: 把两行文字写进文件
 *   步骤2: 一行一行读回来（观察 fgets 读到了什么）
 *   步骤3: 用 strtok 把一行切成"名字"和"年龄"两段
 *   步骤4: 用 atoi 把年龄字符串变成数字，做计算
 *
 * 学习方法：先原样编译运行一遍，看懂输出；
 * 然后按文件末尾的【练习】逐个修改代码再运行。
 */
#include <stdio.h>    /* fopen, fprintf, fgets, printf */
#include <string.h>   /* strcspn, strtok */
#include <stdlib.h>   /* atoi  ← 原版漏了这个头文件！ */

int main(void)
{
    /* ==================================================
     * 步骤1: 写文件
     * - fopen("hello.txt", "w") : 以写模式打开
     *     文件不存在 → 创建；已存在 → 清空重写
     * - fprintf(f, ...) 和 printf 的区别只是多了一个参数 f，
     *   表示"写到文件里"而不是"打印到屏幕"
     * ================================================== */
    FILE *f = fopen("hello.txt", "w");
    if (f == NULL) {                 /* 好习惯：检查打开是否成功 */
        perror("无法创建文件");
        return 1;
    }
    fprintf(f, "alice|30\nbob|25\n");
    fclose(f);                       /* 写完必须关，否则可能丢数据 */

    /* 运行后可以打开 hello.txt 亲自看看里面写了什么 */

    /* ==================================================
     * 步骤2: 读文件 —— fgets 逐行读
     * fgets(line, sizeof(line), f):
     *   从文件读字符放进 line 数组，遇到换行或读满就停。
     *   成功读到 → 返回 line 地址（真），循环继续
     *   文件读完 → 返回 NULL（假），循环结束
     *
     * ⚠️ 注意：fgets 会把行尾的 '\n' 也一起读进来！
     * ================================================== */
    f = fopen("hello.txt", "r");
    if (f == NULL) {
        perror("无法打开文件");
        return 1;
    }

    char line[256];                  /* 缓冲区：装一整行文字 */
    while (fgets(line, sizeof(line), f)) {

        /* 【调试输出】看看 fgets 到底读到了什么
         * 你会看到输出里名字和年龄没有换行对齐——
         * 因为 line 末尾藏着 '\n' */
        printf("[原始行] <%s>\n", line);

        /* --------------------------------------------------
         * 去掉行尾换行符:
         *   strcspn(line, "\n") = 开头到第一个'\n'之间的字符个数
         *   把那个位置改成 '\0'（字符串结束符）= 截断
         *
         * 例: "alice|30\n" → strcspn 返回 8 → line[8]='\0'
         * 结果: "alice|30"
         * -------------------------------------------------- */
        line[strcspn(line, "\n")] = '\0';

        /* ==================================================
         * 步骤3: strtok 切割字符串
         *
         * 第1次调用: strtok(line, "|")
         *   找到第一个 '|'，把它改成 '\0'，返回第一段的开头。
         *   ⚠️ 原字符串被破坏了！（| 变成了 \0）
         *
         * 第2次调用: strtok(NULL, "|")
         *   传 NULL 表示"继续切刚才那个字符串"，
         *   strtok 内部记住了上次切到哪。
         *   ⚠️ 如果这里再传 line，会从头切，永远得到 "alice"！
         * ================================================== */
        char *name = strtok(line, "|");   /* 第一段: "alice" */
        char *age  = strtok(NULL, "|");   /* 第二段: "30"    */

        /* 【调试输出】看切割结果 */
        printf("[切割后] name=\"%s\" age=\"%s\"\n", name, age);

        /* ==================================================
         * 步骤4: atoi 转数字 + 计算
         * - age 是字符串 "30"，不是数字！不能直接 +1
         * - atoi = Ascii TO Integer，把 "30" 变成整数 30
         * - if 判断防止某行格式不对时用到空指针导致崩溃
         * ================================================== */
        if (name && age)
            printf("%s will be %d\n\n", name, atoi(age) + 1);
    }
    fclose(f);
    return 0;
}

/* ==================== 预期输出 ====================
[原始行] <alice|30
>
[切割后] name="alice" age="30"
alice will be 31

[原始行] <bob|25
>
[切割后] name="bob" age="25"
bob will be 26

==================================================== */

